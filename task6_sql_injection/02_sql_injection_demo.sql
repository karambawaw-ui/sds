-- Шаг 2: Демонстрация SQL-инъекции ' OR '1' = '1'

-- Обычный (легитимный) запрос:
-- Пользователь вводит username = 'admin', password = '12345'
SELECT * FROM users
WHERE username = 'admin' AND password = '12345';

-- SQL-инъекция:
-- Злоумышленник вводит в поле пароля: ' OR '1' = '1
-- Запрос становится:
SELECT * FROM users
WHERE username = 'admin' AND password = '' OR '1' = '1';

-- Условие '1' = '1' всегда истинно, поэтому
-- база данных возвращает ВСЕ записи из таблицы users,
-- и система может авторизовать злоумышленника без пароля.
